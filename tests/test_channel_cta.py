"""CTA overlay is a pure film-clock accessory; no soundbite/VO assets are changed."""
import shutil
import subprocess
import tempfile
import unittest
from pathlib import Path
from PIL import Image, ImageDraw, ImageChops

from channel_cta import (_from_beats, _windows, plan, settings, validate_patch,
                         render_filters, path_for)


class ChannelCTATest(unittest.TestCase):
    def setUp(self):
        self.tmp = tempfile.TemporaryDirectory()
        self.addCleanup(self.tmp.cleanup)
        self.root = Path(self.tmp.name)
        (self.root/'assets').mkdir()
        card=Image.new('RGBA',(350,140),(0,0,0,0))
        ImageDraw.Draw(card).rounded_rectangle((8,8,342,132),radius=18,fill=(230,50,55,220))
        card.save(self.root/'assets/channel_cta.png')
        self.project={'channel_cta_asset':{'file':'channel_cta.png'},
                      'channel_cta':{'enabled':True,'mode':'manual', 'manual_in_s':1.,'manual_out_s':4.}}

    def test_card_is_project_local_and_never_autogenerated(self):
        self.assertIsNotNone(path_for(self.project,self.root))
        self.assertEqual(plan(self.project,self.root)[0]['start_ms'],1000)
        self.assertEqual(plan({'channel_cta':{'enabled':True}},self.root),[])
        self.assertEqual(plan({**self.project,'channel_cta':{'enabled':False}},self.root),[])

    def test_manual_requires_valid_window(self):
        self.project['channel_cta']['manual_out_s']=None
        self.assertEqual(plan(self.project,self.root),[])
        for patch in ({'opacity':1.1},{'position':'centre'}, {'mode':'audio_telepathy'},{'enabled':'yes'},{'manual_in_s':-1}):
            with self.subTest(patch=patch),self.assertRaises(ValueError): validate_patch(patch)

    def test_no_cta_during_original_soundbite(self):
        spans=[{'start_ms':0,'end_ms':5000,'text':'Please subscribe and like my video','beat':'1'}] # not a Beat parser argument
        script='''Beat: 001
Type: DOCUMENTARY SOUND BITE
Master timeline: 00:00:00,000 --> 00:00:02,000
Narration Clock: PAUSED at 00:00:00,000
Narration State: PAUSED (Suspended at 00:00:00,000)
Exact Spoken Dialogue: Subscribe to the channel, please
Full source: S01.mp4
Source IN: 00:00:00,000
Source OUT: 00:00:02,000
Duration: 00:00:02,000
Footage Audio: UNMUTED (100%)
Cut Action: CUT TO PICTURE
Beat: 002
Type: VOICE OVER
Master timeline: 00:00:02,000 --> 00:00:04,000
Narration Clock: RESUMES at 00:00:00,000 --> 00:00:02,000
Narration State: RESUMING
Spoken Narration: Let's examine the police record next.
Full source: S01.mp4
Source IN: 00:00:02,000
Source OUT: 00:00:04,000
Footage Audio: MUTED (0%)
Cut Action: CUT TO PICTURE
'''
        self.project['production_script']={'text':script}
        self.project['channel_cta']['mode']='auto'
        self.assertEqual(plan(self.project,self.root),[])

    def test_automatic_lead_in_and_closing_comments_are_distinct(self):
        spans=[{'start_ms':5000,'end_ms':7000,'text':'If you value conversations like this,','beat':'3'},
              {'start_ms':7000,'end_ms':9800,'text':'Please like, subscribe, and turn on notifications.','beat':'4'},
              {'start_ms':9800,'end_ms':14000,'text':'Now let us return to the evidence.','beat':'5'},
              {'start_ms':14000,'end_ms':18000,'text':'Tell us what you think in the comments.','beat':'6'}]
        found=_windows(spans)
        # v15: each window also lists the narration lines that triggered it.
        self.assertEqual([{k:w[k] for k in ('start_ms','end_ms','beats','origin')} for w in found],
                         [{'start_ms':5000,'end_ms':9800,'beats':['3','4'],'origin':'narrator script'}])
        self.assertTrue(any(m['trigger'] for m in found[0]['matches']))

    def test_real_production_script_detects_08_23_cta(self):
        path=Path('/mnt/data/Maleah_Davis_production_script (5).txt')
        if not path.is_file():self.skipTest('User script not mounted')
        rows=_from_beats(path.read_text())
        self.assertEqual(len(rows),93)
        self.assertEqual([(w['start_ms'],w['end_ms']) for w in _windows(rows)],[(503230,512130)])

    @unittest.skipUnless(shutil.which('ffmpeg'), 'FFmpeg not installed')
    def test_ffmpeg_real_slide_fade_render(self):
        args,steps,count=render_filters(self.project,self.root,None,640,360,'30',self.root,1,between=(0,180))
        self.assertEqual(count,1)
        graph=['[0:v]setpts=PTS-STARTPTS[base]']+steps+['[cta]format=yuv420p[out]']
        out=self.root/'movie.mp4'
        cmd=['ffmpeg','-hide_banner','-loglevel','error','-y','-f','lavfi','-i','color=c=blue:s=640x360:r=30:d=6',
             *args,'-filter_complex',';'.join(graph),'-map','[out]','-an','-c:v','mpeg4','-q:v','4',str(out)]
        subprocess.run(cmd,check=True,timeout=30,capture_output=True)
        images=[]
        for t in (.5,1.25,2.0,3.5,4.5):
            f=self.root/f'frame{t}.png'
            subprocess.run(['ffmpeg','-v','error','-y','-ss',str(t),'-i',str(out),'-frames:v','1',str(f)],check=True,timeout=10,capture_output=True)
            images.append(Image.open(f).convert('RGB'))
        # The card is absent outside the window; visible and changing inside it.
        self.assertIsNone(ImageChops.difference(images[0],images[4]).getbbox())
        self.assertIsNotNone(ImageChops.difference(images[0],images[2]).getbbox())
        self.assertIsNotNone(ImageChops.difference(images[1],images[2]).getbbox())

    @unittest.skipUnless(shutil.which('ffmpeg'), 'FFmpeg not installed')
    def test_film_clock_survives_picture_piece_boundary(self):
        for f0,frames in ((0,75),(75,105)):
            args,steps,count=render_filters(self.project,self.root,None,640,360,'30',self.root,1,between=(f0,f0+frames),cache={})
            self.assertEqual(count,1)
            graph=[f'[0:v]setpts=PTS+{f0}/(30*TB)[base]']+steps+['[cta]setpts=PTS-STARTPTS,format=yuv420p[out]']
            cmd=['ffmpeg','-hide_banner','-loglevel','error','-y','-f','lavfi','-i',f'color=c=blue:s=640x360:r=30:d={frames/30}',
                 *args,'-filter_complex',';'.join(graph),'-map','[out]','-frames:v',str(frames),'-an','-c:v','mpeg4','-q:v','4',str(self.root/f'piece{f0}.mp4')]
            subprocess.run(cmd,check=True,timeout=30,capture_output=True)
        self.assertTrue((self.root/'piece75.mp4').stat().st_size>10000)

if __name__=='__main__': unittest.main()
