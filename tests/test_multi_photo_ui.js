const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const code=fs.readFileSync(path.join(__dirname,'../static/person_overlays.js'),'utf8');
const photos=Array.from({length:5},(_,i)=>({path:'people/'+i+'.jpg',uploaded:i}));
const mentions=Array.from({length:240},(_,i)=>({cue:i+1,ms:i*1000,text:'Maleah Davis was mentioned',said:'Maleah Davis',blocked:'',short:false,footage:false}));
const P={id:'test-id',edit_mode:'documentary',people:[{id:'p1',name:'Maleah Davis',role:'Victim',photo:photos[0],photos,show:true,photo_over_video:true}],assets:[],
 person_overlays:{settings:{enabled:true,smart_photo_mode:true,style:'full'},people:[{id:'p1',has_photo:true,windows:24}],moments:{p1:mentions},windows:Array.from({length:24},(_,i)=>({person_id:'p1',start_ms:i*10000,end_ms:i*10000+3000,photo_index:i%5}))}};
const ctx={P,Math,Set,Map,encodeURIComponent,window:{},E:(x)=>String(x).replace(/[&<>"']/g,x=>({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[x]))};
vm.createContext(ctx);
vm.runInContext(code,ctx);
const html=vm.runInContext('peopleCardHTML()',ctx);
assert.match(html,/5 of 5 photos/);
assert.match(html,/Add photo/);
assert.match(html,/Replace first photo/);
assert.match(html,/photo\?index=4/);
assert.match(html,/240 lines name Maleah Davis/);
assert.doesNotMatch(html,/line 240 ·/,'Long SRT lines should not be mounted initially.');
const list={innerHTML:'',dataset:{}};
const details={open:true,querySelector:(q)=>q==='ul'?list:null};
ctx.mountPersonMoments(details,'p1');
assert.match(list.innerHTML,/line 240 ·/);
assert.equal((list.innerHTML.match(/<li/g)||[]).length,240);
const find=t=>ctx.personOverlayAt(t)?.photo_index;
assert.equal(find(0.5),0);
assert.equal(find(10.5),1);
assert.equal(find(40.5),4);
assert.equal(find(50.5),0);
assert.equal(find(3.5),undefined);
console.log('PASS: gallery 5/5, add/replace, lazy SRT expansion (240 lines), binary per-frame lookup and rotation');
